"""
Pydantic v2 models for the sim service — mirror of contracts.ts §4.
Source of truth: packages/contracts/schemas/*.json (generated by CI).
"""
from __future__ import annotations
from typing import Literal, Optional, Union, Annotated
from pydantic import BaseModel, Field
import uuid


# ── Primitive ────────────────────────────────────────────────────────────────
# [lng, lat] WGS84 — matches TypeScript `type LngLat = [number, number]`
LngLat = tuple[float, float]


class Range(BaseModel):
    p10: float
    p50: float
    p90: float


# ── Scenario edits (discriminated union on "type") ───────────────────────────

class EditCloseRoad(BaseModel):
    type: Literal["close_road"]
    wayIds: list[int]


class EditBusLane(BaseModel):
    type: Literal["bus_lane"]
    wayIds: list[int]


class EditRemoveLane(BaseModel):
    type: Literal["remove_lane"]
    wayIds: list[int]


class EditAddTrees(BaseModel):
    type: Literal["add_trees"]
    geometry: list[LngLat]
    count: int
    side: Optional[Literal["north", "south", "east", "west", "both"]] = None


class EditCoolPavement(BaseModel):
    type: Literal["cool_pavement"]
    wayIds: list[int]


ScenarioEdit = Annotated[
    Union[EditCloseRoad, EditBusLane, EditRemoveLane, EditAddTrees, EditCoolPavement],
    Field(discriminator="type"),
]


# ── Scenario ─────────────────────────────────────────────────────────────────

class Scenario(BaseModel):
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    title: str
    edits: list[ScenarioEdit]
    when: str                           # ISO datetime
    origin: Literal["user", "agent_variant"]
    parentId: Optional[str] = None


# ── SimResult ─────────────────────────────────────────────────────────────────

class TrafficSegment(BaseModel):
    wayId: int
    baseFlow: float
    newFlow: float
    baseTimeS: float
    newTimeS: float
    path: Optional[list[LngLat]] = None


class Trip(BaseModel):
    path: list[LngLat]
    departS: float
    durationS: float


class TrafficPart(BaseModel):
    segments: list[TrafficSegment]
    corridorTravelTimeDeltaPct: Range
    vehicleKmDeltaPct: Range
    trips: list[Trip]


class ThermalCell(BaseModel):
    lngLat: LngLat
    baseC: float
    newC: float


class ThermalPart(BaseModel):
    when: str
    cells: list[ThermalCell]
    hotspotDeltaC: Range


class EmissionsPart(BaseModel):
    co2DeltaPct: Range


class SimResult(BaseModel):
    scenarioId: str
    status: Literal["ok", "error"]
    computeMs: int
    traffic: TrafficPart
    thermal: ThermalPart
    emissions: EmissionsPart
    notes: list[str]


# ── Backtest ──────────────────────────────────────────────────────────────────

class ChartPoint(BaseModel):
    predicted: float
    observed: float


class Backtest(BaseModel):
    model: Literal["traffic", "thermal"]
    metric: Literal["MAPE", "MAE_C", "R2"]
    value: float
    heldOut: str
    nSamples: int
    chart: list[ChartPoint]


# ── Resolve response ──────────────────────────────────────────────────────────

class ResolveMatch(BaseModel):
    wayId: int
    name: str
    score: float            # 0–1 fuzzy match confidence
    distM: float            # distance from query geometry to Σεράφειο (m)


class ResolveResponse(BaseModel):
    matches: list[ResolveMatch]


# ── Health ────────────────────────────────────────────────────────────────────

class HealthResponse(BaseModel):
    status: Literal["ok", "degraded"]
    mock: bool
    graph_nodes: Optional[int] = None
    graph_edges: Optional[int] = None
    thermal_model: Optional[str] = None   # "physics" | "ridge" | "lgbm"
    backtests_ready: bool = False
